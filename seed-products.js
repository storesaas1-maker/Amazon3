// ======================================================
// دالة إنشاء رابط صورة مختلف لكل منتج
// ======================================================

function getImageUrl(productNumber, productName) {
  const query = encodeURIComponent(productName);

  return `https://loremflickr.com/800/800/${query}?lock=${productNumber}`;
}


// ======================================================
// تشغيل الـ Seed
// ======================================================

async function seed() {

  try {

    // -----------------------------------------------
    // التأكد من وجود MONGO_URL
    // -----------------------------------------------

    if (!process.env.MONGO_URL) {
      throw new Error(
        "MONGO_URL غير موجود داخل ملف .env"
      );
    }


    // -----------------------------------------------
    // الاتصال بقاعدة البيانات
    // -----------------------------------------------

    await mongoose.connect(process.env.MONGO_URL);

    console.log("تم الاتصال بقاعدة البيانات بنجاح");


    // -----------------------------------------------
    // إنشاء Map للأقسام
    // -----------------------------------------------

    const sectionMap = new Map();


    // -----------------------------------------------
    // إنشاء الأقسام بدون تكرار
    // -----------------------------------------------

    for (const sectionName of sections) {

      let section = await Section.findOne({
        name: sectionName,
      });


      if (!section) {

        section = await Section.create({
          name: sectionName,
        });

        console.log(
          `تم إنشاء القسم: ${sectionName}`
        );

      } else {

        console.log(
          `القسم موجود بالفعل: ${sectionName}`
        );

      }


      sectionMap.set(
        sectionName,
        section._id
      );
    }


    // -----------------------------------------------
    // عدادات
    // -----------------------------------------------

    let inserted = 0;
    let skipped = 0;


    // -----------------------------------------------
    // إضافة المنتجات
    // -----------------------------------------------

    for (const product of products) {

      const [
        name,
        description,
        price,
        discount,
        quantity,
        sectionName,
        imageNumber,
      ] = product;


      // الحصول على ID القسم
      const sectionId =
        sectionMap.get(sectionName);


      if (!sectionId) {

        throw new Error(
          `القسم غير موجود: ${sectionName}`
        );

      }


      // ---------------------------------------------
      // منع تكرار المنتج
      // ---------------------------------------------

      const existingProduct =
        await Product.findOne({
          name: name,
        });


      if (existingProduct) {

        skipped++;

        console.log(
          `تم تخطي المنتج لأنه موجود بالفعل: ${name}`
        );

        continue;
      }


      // ---------------------------------------------
      // حساب السعر النهائي
      // ---------------------------------------------

      const final_price = Number(
        (
          price -
          (price * discount) / 100
        ).toFixed(2)
      );


      // ---------------------------------------------
      // رابط صورة مختلف
      // ---------------------------------------------

      const imageUrl =
        getImageUrl(
          imageNumber,
          name
        );


      // ---------------------------------------------
      // إنشاء المنتج
      // ---------------------------------------------

      await Product.create({

        name: name,

        description: description,

        price: price,

        discount: discount,

        final_price: final_price,

        images: [
          imageUrl
        ],

        section: sectionId,

        reviews: [],

        quantity: quantity,

      });


      inserted++;

      console.log(
        `تم إضافة المنتج: ${name}`
      );
    }


    // ---------------------------------------------
    // النتيجة
    // ---------------------------------------------

    console.log("");
    console.log("================================");
    console.log("تم الانتهاء من إضافة البيانات");
    console.log("================================");

    console.log(
      `عدد الأقسام: ${sections.length}`
    );

    console.log(
      `عدد المنتجات في الملف: ${products.length}`
    );

    console.log(
      `تمت إضافة: ${inserted}`
    );

    console.log(
      `تم تخطي: ${skipped}`
    );

    console.log(
      "================================"
    );


    // ---------------------------------------------
    // إغلاق الاتصال
    // ---------------------------------------------

    await mongoose.disconnect();

    console.log(
      "تم إغلاق اتصال MongoDB"
    );

  } catch (error) {

    console.error("");
    console.error(
      "حصل خطأ أثناء تشغيل Seed:"
    );

    console.error(error);

    await mongoose
      .disconnect()
      .catch(() => {});

    process.exit(1);
  }
}


// ======================================================
// تشغيل
// ======================================================

seed();